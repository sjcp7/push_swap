#include "libft.h"

void	ft_lstadd_front(t_list **lst, t_list *new)
{
	if (lst == NULL)
		return ;
	if (new == NULL)
	{
		*lst = NULL;
		return ;
	}
	new->next = *lst;
	*lst = new;
}
